#include <iostream>

int main(){

    //nested loops
    //we print the table of 5 three times using nested loops
    for (int i = 1; i <= 5; i++)
    {
        for (int j = 3; j <= 30; j+=3)
        {
            std::cout << j << " ";
        }
       std::cout <<"\n";
    }
    

   
    

}